"""Module #4: generated Sigma, Elastic (ES|QL + Kibana rule import) and Sentinel (KQL) output.

Checks that every rule builds for every target, that the output has the structure each platform requires
(Sigma per SigmaHQ conventions, including correlation rules), and that the logic was translated faithfully.
Output must be deterministic so a rebuild never changes rule IDs in a SIEM.
"""

import json
import uuid

import pytest
import yaml

from usbhawk.detections import TARGETS, build, load_rules
from usbhawk.scoring import load_config

RULES = load_rules()


def out(target, rules=RULES):
    return build(rules, target)


def files(target, suffix, rules=RULES):
    return {k: v for k, v in out(target, rules).items() if k.endswith(suffix)}


def one(target, fragment, suffix, rules=RULES):
    hits = [v for k, v in files(target, suffix, rules).items() if fragment in k]
    assert len(hits) == 1, (fragment, list(files(target, suffix, rules)))
    return hits[0]


def sigma_docs(fragment):
    return list(yaml.safe_load_all(one("sigma", fragment, ".yml")))


def ny_rules():
    cfg = load_config()
    cfg["work_hours"]["timezone"] = "America/New_York"
    return load_rules(cfg=cfg)


def balanced(text):
    depth, quote = 0, False
    i = 0
    while i < len(text):
        c = text[i]
        if quote:
            if c == "\\":
                i += 1
            elif c == '"':
                quote = False
        elif c == '"':
            quote = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth < 0:
                return False
        i += 1
    return depth == 0 and not quote


# --------------------------------------------------------------------------- all targets
def test_targets():
    assert {"sigma", "elastic", "sentinel"} <= set(TARGETS)


@pytest.mark.parametrize("target", ["sigma", "elastic", "sentinel"])
def test_every_detection_is_built_or_explained_for_every_target(target):
    built = out(target)
    for r in RULES:
        for d in r.detections:
            want = (f"usbhawk_{r.hypothesis.lower()}_{d['name']}." if target == "sigma"
                    else f"{r.hypothesis}_{r.name}__{d['name']}.")
            assert any(want in k for k in built), (target, want)


