def test_elastic_off_hours_uses_standard_offset():
    utc = one("elastic", "usb_storage_off_hours", ".esql")
    assert "| EVAL usbhawk_local = @timestamp\n" in utc
    assert "usbhawk_hour < 8 OR usbhawk_hour >= 18 OR usbhawk_dow NOT IN (1, 2, 3, 4, 5)" in utc
    ny = one("elastic", "usb_storage_off_hours", ".esql", ny_rules())
    assert "@timestamp - 300 minutes" in ny and "daylight saving" in ny


def test_elastic_rule_import_file():
    lines = [l for l in out("elastic")["elastic/usbhawk_rules.ndjson"].splitlines() if l.strip()]
    rules = [json.loads(l) for l in lines]
    assert len(rules) == sum(len(r.detections) for r in RULES)
    for r in rules:
        assert r["type"] == "esql" and r["language"] == "esql" and r["enabled"] is False
        assert str(uuid.UUID(r["rule_id"])) == r["rule_id"]
        assert r["severity"] in {"low", "medium", "high", "critical"} and 0 < r["risk_score"] <= 100
        assert r["threat"][0]["framework"] == "MITRE ATT&CK" and r["threat"][0]["technique"]
        assert "usbhawk" in r["tags"]
    assert len({r["rule_id"] for r in rules}) == len(rules)
    first_seen = next(r for r in rules if "Not Seen in 30 Days" in r["name"])
    assert first_seen["from"] == "now-30d"
    h7 = next(r for r in rules if "1102" in r["name"])
    assert h7["threat"][0]["tactic"]["id"] == "TA0112"
    assert h7["threat"][0]["technique"][0]["subtechnique"][0]["id"] == "T1685.005"


def test_elastic_and_sigma_ids_agree():
    sigma_ids = {doc["id"] for _n, doc in all_sigma_docs() if "name" not in doc}   # skip correlation base rules
    elastic = {json.loads(l)["rule_id"] for l in out("elastic")["elastic/usbhawk_rules.ndjson"].splitlines() if l}
    unsupported = len(files("sigma", ".unsupported.txt"))
    assert sigma_ids <= elastic and len(elastic - sigma_ids) == unsupported


