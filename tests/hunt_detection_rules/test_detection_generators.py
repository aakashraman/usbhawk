# --------------------------------------------------------------------------- Sigma
REQUIRED_RULE = {"title", "id", "status", "description", "author", "date", "tags", "logsource", "detection",
                 "falsepositives", "level"}
REQUIRED_CORRELATION = {"title", "id", "status", "author", "date", "correlation", "level"}


def all_sigma_docs():
    for name, text in files("sigma", ".yml").items():
        for doc in yaml.safe_load_all(text):
            yield name, doc


def test_sigma_structure_and_unique_ids():
    ids = []
    for name, doc in all_sigma_docs():
        required = REQUIRED_CORRELATION if "correlation" in doc else REQUIRED_RULE
        assert required <= set(doc), (name, required - set(doc))
        if "detection" in doc:
            assert "condition" in doc["detection"]
        assert doc["level"] in {"low", "medium", "high", "critical"}
        assert any(t.startswith("attack.t") for t in doc["tags"]) and all(t == t.lower() for t in doc["tags"])
        ids.append(str(uuid.UUID(doc["id"])))
    assert len(ids) == len(set(ids))


