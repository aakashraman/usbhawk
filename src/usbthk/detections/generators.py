"""Translate neutral rules into Sigma, Elastic (ES|QL + Kibana rule import) and Microsoft Sentinel (KQL).

Every generator implements the reference semantics of core.evaluate()/evaluate_stream(): case-insensitive values,
a list means any-of (|all: every value), all fields in a selection must match, conditions use and/or/not.
Output is deterministic: the same rules always give byte-identical files and the same rule IDs.

What a platform cannot express is said out loud instead of silently weakened:
  Sigma has no "first seen" and no time-of-day logic -> a .unsupported.txt explaining why;
  thresholds become a Sigma correlation rule (event_count) on top of a named base rule.
Sigma field names and log sources follow SigmaHQ (process_creation, file_event, registry_delete, security 6416).
"""

from __future__ import annotations

import json
from datetime import datetime
from zoneinfo import ZoneInfo

import yaml

from . import attack
from .core import Rule, parse_condition, parse_key

TARGETS = ("sigma", "elastic", "sentinel")
ELASTIC_INDEX = "logs-*, winlogbeat-*"           # Elastic Agent integrations and Winlogbeat
RISK = {"low": 21, "medium": 47, "high": 73, "critical": 99}
NUMERIC = {"event_id"}


def _values(v) -> list:
    return v if isinstance(v, list) else [v]


def _header(rule: Rule, det: dict, comment: str) -> str:
    level = rule.level_of(det["name"])
    lines = [f"{rule.title}: {det.get('title', det['name'])}",
             f"hypothesis {rule.hypothesis} | level {level} | ATT&CK {', '.join(rule.data['attack'])} | "
             f"offline hunt: usbthk {rule.data.get('usbthk', '-')}",
             f"generated by usbthk from {rule.path.name} - edit the YAML source, not this file"]
    return "".join(f"{comment} {line}\n" for line in lines)


def _title(rule: Rule, det: dict) -> str:
    return f"{rule.title} ({det['title']})" if det.get("title") and len(rule.detections) > 1 else rule.title


def _stem(rule: Rule, det: dict) -> str:
    return f"{rule.hypothesis}_{rule.name}__{det['name']}"


def _description(rule: Rule) -> str:
    return " ".join(str(rule.data["description"]).split())


def _translate(tree, render_sel, and_, or_, not_) -> str:
    op = tree[0]
    if op == "sel":
        return render_sel(tree[1])
    if op == "not":
        return not_(_translate(tree[1], render_sel, and_, or_, not_))
    a = _translate(tree[1], render_sel, and_, or_, not_)
    b = _translate(tree[2], render_sel, and_, or_, not_)
    return f"({a} {and_ if op == 'and' else or_} {b})"


def _standard_offset_minutes(tz: str) -> int:
    """UTC offset of the zone's standard (non-DST) time: the smaller of January's and July's offsets."""
    z = ZoneInfo(tz)
    offs = [datetime(2026, m, 15, 12, tzinfo=z).utcoffset().total_seconds() // 60 for m in (1, 7)]
    return int(min(offs))


# =========================================================================== Sigma
SIGMA_LOGSOURCE = {
    "process_creation": {"category": "process_creation", "product": "windows"},
    "file_event": {"category": "file_event", "product": "windows"},
    "registry_event": {"category": "registry_delete", "product": "windows"},
    "device_connect": {"product": "windows", "service": "security"},
}
SIGMA_FIELDS = {
    "process_creation": {"image": "Image", "command_line": "CommandLine", "original_file_name": "OriginalFileName",
                         "parent_image": "ParentImage", "user": "User", "host": "Computer"},
    "event_log": {"event_id": "EventID", "provider": "Provider_Name", "user": "SubjectUserName", "host": "Computer"},
    "device_connect": {"device_id": "DeviceId", "device_class": "ClassName", "device_description": "DeviceDescription",
                       "user": "SubjectUserName", "host": "Computer"},
    "file_event": {"file_path": "TargetFilename", "image": "Image", "user": "User", "host": "Computer"},
    "registry_event": {"registry_path": "TargetObject", "image": "Image", "user": "User", "host": "Computer"},
}
# Sigma has no basename fields: a name is matched on the path field instead (as SigmaHQ rules do).
SIGMA_NAME_FIELDS = {"process_name": "Image", "parent_name": "ParentImage", "file_name": "TargetFilename"}
# SigmaHQ filename prefixes per log source (pySigma-validators-sigmahq data_filename).
SIGMA_PREFIX = {"process_creation": "proc_creation_win_", "file_event": "file_event_win_",
                "registry_event": "registry_delete_", "device_connect": "win_security_"}


def sigma_filename(rule: Rule, det: dict, suffix: str = ".yml") -> str:
    """SigmaHQ-style name: <logsource prefix>usbthk_<hyp>_<detection>; correlations start with correlation_."""
    tel = det["telemetry"]
    if det.get("threshold") and suffix == ".yml":
        prefix = "correlation_"
    elif tel == "event_log":
        prefix = f"win_{det['channel'].lower()}_"
    else:
        prefix = SIGMA_PREFIX[tel]
    return f"{prefix}usbthk_{rule.hypothesis.lower()}_{det['name']}{suffix}"


def _sigma_key(tel: str, key: str, values: list) -> tuple[str, list]:
    name, mod, every = parse_key(key)
    suffix = "|all" if every else ""
    if name in SIGMA_NAME_FIELDS:
        field = SIGMA_NAME_FIELDS[name]
        if mod == "eq":
            return f"{field}|endswith{suffix}", ["\\" + str(v) for v in values]
        if mod == "startswith":
            return f"{field}|contains{suffix}", ["\\" + str(v) for v in values]
        return f"{field}|{mod}{suffix}", values
    field = SIGMA_FIELDS[tel][name]
    return (field if mod == "eq" else f"{field}|{mod}{suffix}"), values


def _sigma_detection(rule: Rule, det: dict) -> dict:
    tel = det["telemetry"]
    detection, extra = {}, []
    if tel == "device_connect":
        detection["usbthk_pnp_6416"] = {"EventID": 6416}
        extra.append("usbthk_pnp_6416")
    if det.get("removable_media"):
        # Sysmon file events carry no "removable" flag: files on drives D:-Z: (heuristic, see falsepositives)
        detection["usbthk_removable_drive"] = {"TargetFilename|re": "^[D-Zd-z]:\\\\"}
        extra.append("usbthk_removable_drive")
    for sname, sel in (det.get("selections") or {}).items():
        out = {}
        for key, v in sel.items():
            skey, vals = _sigma_key(tel, key, _values(v))
            if skey in out:
                raise ValueError(f"{rule.name}.{det['name']}.{sname}: two fields map to Sigma {skey}")
            out[skey] = vals[0] if len(vals) == 1 else vals
        detection[sname] = out
    parts = extra + ([f"({det['condition']})" if extra else det["condition"]] if det.get("condition") else [])
    detection["condition"] = " and ".join(parts)
    return detection


def _sigma_doc(rule: Rule, det: dict, ident: str, title: str) -> dict:
    tel = det["telemetry"]
    doc = {"title": title, "id": ident}
    related = [{"id": r["id"], "type": "similar"} for r in det.get("related") or []]
    if related:
        doc["related"] = related
    doc.update({
        "status": "experimental",
        "description": _description(rule),
        # SigmaHQ: ATT&CK is expressed by tags, never by attack.mitre.org links in references
        "references": [r for r in rule.data.get("references") or [] if "attack.mitre.org" not in r],
        "author": "usbthk",
        "date": str(rule.data["date"]),
        "tags": attack.sigma_tags(rule.data["attack"]),
        "logsource": (SIGMA_LOGSOURCE[tel] if tel != "event_log"
                      else {"product": "windows", "service": det["channel"].lower()}),
        "detection": _sigma_detection(rule, det),
        "falsepositives": rule.data.get("false_positives") or ["Unknown"],
        "level": rule.level_of(det["name"]),
    })
    if not doc["references"]:
        del doc["references"]
    return doc


def _dump(doc: dict) -> str:
    return yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=110)


def sigma(rule: Rule, det: dict) -> tuple[str, str]:
    """(file suffix, content): '.yml' for a rule (plus correlation), '.unsupported.txt' when Sigma cannot say it."""
    header = _header(rule, det, "#")
    why = []
    if det.get("first_seen"):
        why.append("'first seen in N days' needs the platform's history (Sigma has no new-value rule type)")
    if det.get("outside_work_hours"):
        why.append("time-of-day / weekday conditions on a local clock cannot be expressed in Sigma")
    if why:
        return ".unsupported.txt", (header + "#\n# Not generated for Sigma: " + "; ".join(why) + ".\n"
                                    "# Use the Elastic (ES|QL) or Sentinel (KQL) version of this detection.\n")
    th = det.get("threshold")
    if not th:
        return ".yml", header + _dump(_sigma_doc(rule, det, rule.detection_id(det["name"]), _title(rule, det)))
    # Threshold: a named base rule + a Sigma correlation rule (event_count) that references it.
    base_name = f"usbthk_{rule.hypothesis.lower()}_{det['name']}"
    base = _sigma_doc(rule, det, rule.sub_id(det["name"], "base"), f"{_title(rule, det)} - Single Event")
    base = {"title": base["title"], "id": base["id"], "name": base_name,
            **{k: v for k, v in base.items() if k not in ("title", "id")}}
    base["level"] = "low"
    fields = {**SIGMA_FIELDS[det["telemetry"]], **SIGMA_NAME_FIELDS}
    corr = {
        "title": _title(rule, det),
        "id": rule.detection_id(det["name"]),
        "status": "experimental",
        "description": _description(rule),
        "author": "usbthk",
        "date": str(rule.data["date"]),
        "tags": attack.sigma_tags(rule.data["attack"]),
        "correlation": {
            "type": "event_count",
            "rules": [base_name],
            "group-by": [fields[f] for f in th.get("by", [])],
            "timespan": f"{int(th['window_minutes'])}m",
            "condition": {"gte": int(th["count"])},
        },
        "falsepositives": rule.data.get("false_positives") or ["Unknown"],
        "level": rule.level_of(det["name"]),
    }
    return ".yml", header + _dump(base) + "---\n" + _dump(corr)


