def _kql_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _kql_cond(fields: dict, key: str, values: list) -> str:
    name, mod, every = parse_key(key)
    field = fields[name]
    if name in NUMERIC:
        nums = ", ".join(str(int(v)) for v in values)
        return f"{field} == {nums}" if len(values) == 1 else f"{field} in ({nums})"
    if mod == "eq" and not every:
        return (f"{field} =~ {_kql_str(str(values[0]))}" if len(values) == 1
                else f"{field} in~ ({', '.join(_kql_str(str(v)) for v in values)})")
    op = "=~" if mod == "eq" else mod            # contains/startswith/endswith are case-insensitive in KQL
    parts = [f"{field} {op} {_kql_str(str(v))}" for v in values]
    return parts[0] if len(parts) == 1 else "(" + (" and " if every else " or ").join(parts) + ")"


def kql(rule: Rule, det: dict) -> str:
    tel = det["telemetry"]
    prelude, fields, tcol, project, sample = KQL[(tel, det.get("channel") if tel == "event_log" else None)]
    lines = list(prelude)
    fs, th, wh = det.get("first_seen"), det.get("threshold"), det.get("outside_work_hours")
    if fs:
        lines.append(f"| where {tcol} > ago({int(fs['lookback_days'])}d)")
    if det.get("removable_media"):           # MDE knows which drive letters are USB: join, no guessing
        lines = [_USB_DRIVES] + lines + ["| extend DriveLetter = toupper(substring(FolderPath, 0, 2))",
                                         "| join kind=inner UsbDrives on DeviceId, DriveLetter"]
    if det.get("condition"):
        sels = {n: " and ".join(_kql_cond(fields, k, _values(v)) for k, v in s.items())
                for n, s in det["selections"].items()}
        logic = _translate(parse_condition(det["condition"]), lambda n: f"({sels[n]})", "and", "or",
                           lambda x: f"not{x if x.startswith('(') else '(' + x + ')'}")
        lines.append(f"| where {logic}")
    if wh:
        days = ", ".join(str((d + 1) % 7) for d in wh["workdays"])    # KQL dayofweek: Sunday = 0
        lines += [f'| extend LocalTime = datetime_utc_to_local({tcol}, "{wh["timezone"]}")',
                  f"| where hourofday(LocalTime) < {wh['start_hour']} or hourofday(LocalTime) >= {wh['end_hour']} "
                  f"or toint(dayofweek(LocalTime) / 1d) !in ({days})"]
    if th:
        by = ", ".join(fields[f] for f in th.get("by", []))
        lines += [f"| summarize Events = count(), FirstEvent = min({tcol}), LastEvent = max({tcol}), "
                  f"Sample = make_set({sample}, 25) by {by + ', ' if by else ''}"
                  f"bin({tcol}, {int(th['window_minutes'])}m)",
                  f"| where Events >= {int(th['count'])}"]
    elif fs:
        lines += [f"| summarize FirstSeen = min({tcol}), LastSeen = max({tcol}), Connects = count(), "
                  f"Hosts = make_set({fields['host']}, 25) by {fields[fs['by']]}",
                  f"| where FirstSeen > ago({int(fs['window_minutes'])}m)"]
    else:
        lines.append(f"| project {', '.join(project + (['LocalTime'] if wh else []))}")
    return "\n".join(lines) + "\n"


# =========================================================================== build
def build(rules: list[Rule], target: str) -> dict[str, str]:
    """{relative output path: file content} for one target."""
    if target not in TARGETS:
        raise ValueError(f"unknown target {target!r}; choose from {', '.join(TARGETS)}")
    out: dict[str, str] = {}
    imports = []
    for rule in rules:
        for det in rule.detections:
            stem = _stem(rule, det)
            if target == "sigma":
                suffix, text = sigma(rule, det)
                out[f"sigma/{sigma_filename(rule, det, suffix)}"] = text
            elif target == "elastic":
                out[f"elastic/{stem}.esql"] = _header(rule, det, "//") + esql(rule, det)
                imports.append(json.dumps(elastic_rule(rule, det), sort_keys=True))
            else:
                out[f"sentinel/{stem}.kql"] = _header(rule, det, "//") + kql(rule, det)
    if target == "elastic":
        out["elastic/usbthk_rules.ndjson"] = "\n".join(imports) + "\n"
    return out
