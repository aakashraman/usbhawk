def _esql_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _esql_like(s: str) -> str:
    return s.replace("\\", "\\\\").replace("*", "\\*").replace("?", "\\?")


def _esql_cond(fields: dict, key: str, values: list) -> str:
    name, mod, every = parse_key(key)
    field = fields[name]
    parts = []
    for v in values:
        if name in NUMERIC:                        # ECS event.code is a keyword string
            parts.append(f"{field} == {_esql_str(str(v))}")
            continue
        low = str(v).lower()
        if mod == "eq":
            parts.append(f"TO_LOWER({field}) == {_esql_str(low)}")
        elif mod == "startswith":
            parts.append(f"STARTS_WITH(TO_LOWER({field}), {_esql_str(low)})")
        elif mod == "endswith":
            parts.append(f"ENDS_WITH(TO_LOWER({field}), {_esql_str(low)})")
        else:
            parts.append(f"TO_LOWER({field}) LIKE {_esql_str('*' + _esql_like(low) + '*')}")
    joiner = " AND " if every else " OR "
    return parts[0] if len(parts) == 1 else "(" + joiner.join(parts) + ")"


def esql(rule: Rule, det: dict) -> str:
    tel = det["telemetry"]
    base, fields, keep, sample = ECS[tel]
    where = list(base)
    if tel == "event_log":
        where.append(f"winlog.channel == {_esql_str(det['channel'])}")
    if det.get("removable_media"):    # no "removable" flag in ECS file events: drives D:-Z: (heuristic)
        where.append('SUBSTRING(file.path, 2, 1) == ":" AND NOT STARTS_WITH(TO_LOWER(file.path), "c:")')
    if det.get("condition"):
        sels = {n: " AND ".join(_esql_cond(fields, k, _values(v)) for k, v in s.items())
                for n, s in det["selections"].items()}
        where.append(_translate(parse_condition(det["condition"]), lambda n: f"({sels[n]})", "AND", "OR",
                                lambda x: f"NOT {x}"))
    stateful = det.get("threshold") or det.get("first_seen")
    lines = [f"FROM {ELASTIC_INDEX}" + ("" if stateful else " METADATA _id, _index, _version"),
             f"| WHERE {where[0]}"] + [f"  AND {w}" for w in where[1:]]
    wh = det.get("outside_work_hours")
    if wh:
        off = _standard_offset_minutes(wh["timezone"])
        local = "@timestamp" if off == 0 else f"@timestamp {'+' if off > 0 else '-'} {abs(off)} minutes"
        days = ", ".join(str(d + 1) for d in wh["workdays"])          # ISO day of week: Monday = 1
        lines += [f"// ES|QL has no time zones: {wh['timezone']} at its standard offset ({off:+d} min), "
                  f"so work hours shift by 1 h during daylight saving time",
                  f"| EVAL usbthk_local = {local}",
                  '| EVAL usbthk_hour = DATE_EXTRACT("HOUR_OF_DAY", usbthk_local), '
                  'usbthk_dow = DATE_EXTRACT("DAY_OF_WEEK", usbthk_local)',
                  f"| WHERE usbthk_hour < {wh['start_hour']} OR usbthk_hour >= {wh['end_hour']} "
                  f"OR usbthk_dow NOT IN ({days})"]
    th, fs = det.get("threshold"), det.get("first_seen")
    if th:
        by = ", ".join(fields[f] for f in th.get("by", []))
        lines += [f"| STATS events = COUNT(*), first_event = MIN(@timestamp), last_event = MAX(@timestamp), "
                  f"sample = VALUES({sample}) BY {by + ', ' if by else ''}"
                  f"window = BUCKET(@timestamp, {int(th['window_minutes'])} minutes)",
                  f"| WHERE events >= {int(th['count'])}"]
    elif fs:
        key = fields[fs["by"]]
        lines += [f"| STATS first_seen = MIN(@timestamp), last_seen = MAX(@timestamp), connects = COUNT(*), "
                  f"hosts = VALUES(host.name) BY {key}",
                  f"| WHERE first_seen >= NOW() - {int(fs['window_minutes'])} minutes"]
    else:
        lines.append(f"| KEEP {', '.join(keep + ['_id', '_index', '_version'])}")
    return "\n".join(lines) + "\n"


def elastic_rule(rule: Rule, det: dict) -> dict:
    """One Elastic Security rule (Kibana: Security > Rules > Import), disabled until reviewed."""
    level = rule.level_of(det["name"])
    note = "## Triage\n" + "\n".join(f"- {s}" for s in rule.data.get("response", []))
    th, fs = det.get("threshold"), det.get("first_seen")
    lookback = (f"now-{int(fs['lookback_days'])}d" if fs
                else f"now-{int(th['window_minutes']) + 5}m" if th else "now-9m")
    return {
        "rule_id": rule.detection_id(det["name"]),
        "name": _title(rule, det),
        "description": _description(rule),
        "type": "esql", "language": "esql", "query": esql(rule, det),
        "severity": level, "risk_score": RISK[level],
        "threat": attack.elastic_threat(rule.data["attack"]),
        "tags": ["usbthk", "USB", "OS: Windows", f"Hypothesis: {rule.hypothesis}"]
                + [f"Tactic: {t}" for t in attack.tactic_names(rule.data["attack"])],
        "false_positives": rule.data.get("false_positives") or [],
        "references": rule.data.get("references") or [],
        "note": note, "author": ["usbthk"], "license": "MIT",
        "from": lookback, "interval": "5m", "max_signals": 100, "enabled": False, "version": 1,
    }


